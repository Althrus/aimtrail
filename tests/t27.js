const chromium = require('@sparticuz/chromium').default || require('@sparticuz/chromium');
const puppeteer = require('puppeteer-core'); const B = 'http://127.0.0.1:8900'; const wait = ms => new Promise(r => setTimeout(r, ms));
const ok = (n, c, x = '') => console.log(c ? '  OK   ' : '  GAGAL', n, x);
(async () => {
  const browser = await puppeteer.launch({ args: [...chromium.args, '--no-sandbox'], executablePath: await chromium.executablePath(), headless: 'shell' });
  const page = await browser.newPage(); await page.setViewport({ width: 500, height: 500 }); const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.goto(B + '/dir.html'); await wait(900);
  const drive = (dx, dy, ms) => page.evaluate((dx, dy, ms) => new Promise(res => { const t0 = performance.now(); const iv = setInterval(() => { view.move(dx, dy); if (performance.now() - t0 > ms) { clearInterval(iv); res(); } }, 8); }), dx, dy, ms);
  const cfg = c => page.evaluate(c => view.setConfig(Object.assign({}, view.cfg, c)), c);
  const cs = (sel, prop) => page.evaluate((sel, prop) => getComputedStyle(document.querySelector(sel))[prop], sel, prop);
  const v = name => page.evaluate(n => view.board.style.getPropertyValue(n).trim(), name);
  const settle = () => wait(2600);
  const RED = 'rgb(255, 0, 0)';
  console.log('== mode tema'); await cfg({ style: 'chevron', wm: false, colorMode: 'theme', cMain: '#ff0000' }); await wait(200);
  ok('ikut tema: warna sendiri diabaikan', (await cs('.dr-ch', 'stroke')) !== RED, await cs('.dr-ch', 'stroke'));
  console.log('== mode warna sendiri'); await cfg({ colorMode: 'custom', cMain: '#ff0000', cRing: '#00ff00', cDot: '#0000ff', cTrack: '#123456', cText: '#abcdef' }); await wait(200);
  ok('panah memakai warna utama', (await cs('.dr-ch', 'stroke')) === RED);
  ok('cincin memakai warna lingkaran', (await cs('.dr-ring', 'stroke')) === 'rgb(0, 255, 0)');
  ok('titik pusat memakai warna titik', (await cs('.dr-dot', 'fill')) === 'rgb(0, 0, 255)');
  console.log('== bar & angka'); await cfg({ style: 'bar', showSpeed: true }); await wait(200);
  ok('latar bar memakai warna latar bar', (await cs('.dr-track', 'fill')) === 'rgb(18, 52, 86)');
  ok('isi bar memakai warna utama', (await cs('.dr-fill', 'fill')) === RED);
  ok('angka kecepatan memakai warna teks', (await cs('.dr-val', 'fill')) === 'rgb(171, 205, 239)');
  console.log('== glow, tebal, redup'); await cfg({ style: 'chevron', glowOn: true, glowSize: 12, thick: 16, dim: 0.4 }); await settle();
  ok('besar glow 12 px', (await v('--dr-gs')) === '12px', await v('--dr-gs'));
  ok('glow dimatikan -> 0 px', await (async () => { await cfg({ glowOn: false }); return (await v('--dr-gs')) === '0px'; })());
  ok('ketebalan panah 16 px', (await cs('.dr-ch', 'strokeWidth')) === '16px', await cs('.dr-ch', 'strokeWidth'));
  const idleOp = await page.evaluate(() => Math.min(...view.q.arms.flatMap(a => a.ch.map(p => +p.style.opacity))));
  ok('redup 0,4 -> panah mati tetap terlihat ≈ 0,4', Math.abs(idleOp - 0.4) < 0.03, idleOp.toFixed(2));
  await cfg({ dim: 0 }); await page.evaluate(() => view.draw(performance.now()));
  ok('redup 0 -> panah mati hilang', (await page.evaluate(() => Math.max(...view.q.arms.flatMap(a => a.ch.map(p => +p.style.opacity))))) < 0.01);
  console.log('== warna berubah saat cepat'); await cfg({ dim: 0.14, speedColor: true, cFast: '#00ff00', cMain: '#ff0000' }); await settle();
  ok('diam: warna utama asli', (await v('--t-accent')) === '#ff0000', await v('--t-accent'));
  await drive(90, 0, 700); const hot = await v('--t-accent');
  ok('gerak cepat: bergeser ke warna cepat (hijau naik, merah turun)', parseInt(hot.slice(3, 5), 16) > 150 && parseInt(hot.slice(1, 3), 16) < 100, hot);
  await settle(); ok('kembali ke warna utama setelah diam', (await v('--t-accent')) === '#ff0000', await v('--t-accent'));
  await cfg({ speedColor: false }); await drive(90, 0, 300); await settle();
  ok('fitur dimatikan -> warna tidak berubah', (await v('--t-accent')) === '#ff0000');
  ok('tanpa error JS', errs.length === 0, errs.join('|'));
  await browser.close();
})().catch(e => { console.error('ERR', e.message.slice(0, 300)); process.exit(1); });
